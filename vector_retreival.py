def get_course_embeddings(catalog=None):
    global _course_embeddings_cache
    if _course_embeddings_cache is not None:
        return _course_embeddings_cache

    catalog = catalog or COURSE_CATALOG
    courseids = []
    texts = []
    for courseid, info in catalog.items():
        courseids.append(str(courseid))
        texts.append(info.get("keyword_name") or info.get("name") or str(courseid))

    if not texts:
        _course_embeddings_cache = {}
        return _course_embeddings_cache

    response = openai_client.embeddings.create(
        input=texts,
        model="text-embedding-3-small"
    )
    _course_embeddings_cache = {
        courseid: np.array(item.embedding, dtype=np.float32)
        for courseid, item in zip(courseids, response.data)
    }
    return _course_embeddings_cache


def score_courses_for_query(query, query_terms, embeddedq, catalog=None, course_embeddings=None):
    catalog = catalog or COURSE_CATALOG
    course_embeddings = course_embeddings or get_course_embeddings(catalog)
    scored = []

    for courseid, info in catalog.items():
        keyword_name = info.get("keyword_name") or info.get("name") or ""
        keyword_score = keyword_set_similarity(query_terms, split_fuzzy_keywords(keyword_name))
        fuzzy_score = fuzzy_name_similarity(query_terms, keyword_name)
        course_vector = course_embeddings.get(str(courseid))
        semantic_score = float(np.dot(embeddedq, course_vector)) if course_vector is not None else 0.0
        code_score = course_code_match_score(query, info)
        semantic_fuzzy = semantic_score + fuzzy_score + code_score
        scored.append({
            "courseid": str(courseid),
            "name": info.get("name", ""),
            "keyword_score": max(keyword_score, code_score),
            "fuzzy_score": fuzzy_score,
            "semantic_score": semantic_score,
            "course_code_score": code_score,
            "semantic_fuzzy": semantic_fuzzy,
        })

    scored.sort(
        key=lambda item: (item["course_code_score"], item["keyword_score"], item["semantic_fuzzy"], item["fuzzy_score"]),
        reverse=True
    )
    return scored


def narrow_course_pool(course_pool, focus_course_ids, *, pool_mode=""):
    """Prefer the student's focused course(s) to shrink agent retrieval search."""
    focus_set = {str(course_id) for course_id in (focus_course_ids or []) if course_id}
    if not focus_set:
        return course_pool, pool_mode
    if course_pool:
        narrowed = {str(course_id) for course_id in course_pool if str(course_id) in focus_set}
        if narrowed:
            return narrowed, "focus"
    return focus_set, "focus"


def should_skip_fast_rank(
    fast,
    mode,
    fuzzy_similarity,
    course_similarity,
    *,
    pool_mode=None,
    intent=None,
    single_course_pool=False,
):
    if not fast or mode != "agent":
        return False
    fuzzy = float(fuzzy_similarity or 0.0)
    course = float(course_similarity or 0.0)
    narrow_pool = (
        single_course_pool
        or pool_mode in {"focus", "course_code"}
    )
    if narrow_pool:
        floor = (
            AGENT_FOCUS_SCHEDULE_FUZZY_FLOOR
            if intent in {"deadline", "syllabus", "exam"}
            else AGENT_FOCUS_FUZZY_FLOOR
        )
        return fuzzy < floor
    return fuzzy < AGENT_FAST_FUZZY_FLOOR and course < AGENT_FAST_COURSE_FLOOR


