def find_concept_by_name(name, courseid=None):
    name_lower = str(name or "").strip().lower()
    if not name_lower:
        return None
    scoped = str(courseid or "").strip()
    for concept in allnodes["concepts"]:
        if scoped and str(getattr(concept, "courseid", "")) != scoped:
            continue
        if str(getattr(concept, "name", "")).strip().lower() == name_lower:
            return concept
    for concept in allnodes["concepts"]:
        if scoped and str(getattr(concept, "courseid", "")) != scoped:
            continue
        concept_name = str(getattr(concept, "name", "")).strip().lower()
        if name_lower in concept_name or concept_name in name_lower:
            return concept
    return None


def event_concept_neighbors(event):
    neighbors = []
    seen = set()
    courseid = str(getattr(event, "courseid", "") or "")

    def add_concept(concept):
        if concept is None:
            return
        key = str(getattr(concept, "conceptid", "") or getattr(concept, "name", ""))
        if not key or key in seen:
            return
        seen.add(key)
        neighbors.append(("concept", concept))

    for item in getattr(event, "coveredConcepts", []) or []:
        if isinstance(item, dict):
            concept = find_concept(item.get("conceptid"))
            if concept is None and item.get("name"):
                concept = find_concept_by_name(item.get("name"), courseid)
            add_concept(concept)
        elif isinstance(item, str):
            add_concept(find_concept_by_name(item, courseid))

    for dependency in getattr(event, "dependencies", []) or []:
        if isinstance(dependency, str):
            add_concept(find_concept_by_name(dependency, courseid))

    return neighbors


def node_neighbors(nodetype, node):
    neighbors = []
    if nodetype in {"detail", "example"}:
        child_kind = "details" if nodetype == "detail" else "examples"
        ref_kind = "detail" if nodetype == "detail" else "example"
        for concept in allnodes["concepts"]:
            children = getattr(concept, child_kind, []) or []
            if any(child is node for child in children):
                neighbors.append(("concept", concept))
                child_ref = f"{ref_kind}:{getattr(concept, 'conceptid', '')}:{getattr(node, 'name', '')}"
                for coursefiles in allnodes["files"].values():
                    for filenode in coursefiles.values():
                        file_refs = getattr(filenode, child_kind, []) or []
                        if child_ref in file_refs or getattr(node, "name", "") in file_refs:
                            neighbors.append(("file", filenode))
                break
        return neighbors

    if nodetype == "concept":
        for detail in getattr(node, "details", []) or []:
            neighbors.append(("detail", detail))
        for example in getattr(node, "examples", []) or []:
            neighbors.append(("example", example))
        for problemid in getattr(node, "problems", []) or []:
            problem = find_problem(problemid)
            if problem:
                neighbors.append(("problem", problem))
        conceptid = getattr(node, "conceptid", "")
        for coursefiles in allnodes["files"].values():
            for filenode in coursefiles.values():
                if conceptid and conceptid in (getattr(filenode, "concepts", []) or []):
                    neighbors.append(("file", filenode))
        for assignment in iter_assignments():
            assignment_problems = getattr(assignment, "problems", []) or []
            if any(problemid in assignment_problems for problemid in getattr(node, "problems", []) or []):
                neighbors.append(("assignment", assignment))
        conceptid = getattr(node, "conceptid", "")
        for prereq_id in getattr(node, "prerequisiteConceptIds", []) or []:
            prereq = find_concept(prereq_id)
            if prereq:
                neighbors.append(("concept", prereq))
        for other in allnodes["concepts"]:
            if conceptid and conceptid in (getattr(other, "prerequisiteConceptIds", []) or []):
                neighbors.append(("concept", other))
        for blocks in (allnodes.get("learningBlocks", {}) or {}).values():
            for block in blocks or []:
                if str(block.get("conceptId", "")) == str(conceptid):
                    neighbors.append(("learningBlock", block))
        return neighbors

    if nodetype == "problem":
        for conceptid in (getattr(node, "incomingConceptNodeIds", []) or []) + (getattr(node, "outgoingConceptNodeIds", []) or []):
            concept = find_concept(conceptid)
            if concept:
                neighbors.append(("concept", concept))
        for assignmentid in getattr(node, "assignmentNodeIds", []) or []:
            assignment = find_assignment(assignmentid)
            if assignment:
                neighbors.append(("assignment", assignment))
        problemid = getattr(node, "problemid", "")
        for coursefiles in allnodes["files"].values():
            for filenode in coursefiles.values():
                if problemid and problemid in (getattr(filenode, "problems", []) or []):
                    neighbors.append(("file", filenode))
        for assignment in iter_assignments():
            if problemid and problemid in (getattr(assignment, "problems", []) or []):
                neighbors.append(("assignment", assignment))
        return neighbors

    if nodetype == "assignment":
        for problemid in getattr(node, "problems", []) or []:
            problem = find_problem(problemid)
            if problem:
                neighbors.append(("problem", problem))
        return neighbors

    if nodetype == "file":
        for conceptid in getattr(node, "concepts", []) or []:
            concept = find_concept(conceptid)
            if concept:
                neighbors.append(("concept", concept))
        for problemid in getattr(node, "problems", []) or []:
            problem = find_problem(problemid)
            if problem:
                neighbors.append(("problem", problem))
        return neighbors

    if nodetype == "event":
        eventid = str(getattr(node, "eventid", "") or "")
        courseid = str(getattr(node, "courseid", "") or "")
        for edge in EDGE_LOOKUP.get(("event", eventid), []):
            target_type = str(edge.get("toType") or "")
            target_id = str(edge.get("toId") or "")
            if target_type == "file":
                filenode = find_file(target_id, courseid)
                if filenode and str(getattr(filenode, "courseid", "") or courseid) == courseid:
                    neighbors.append(("file", filenode))
            elif target_type == "concept":
                concept = find_concept(target_id)
                if concept and str(getattr(concept, "courseid", "") or courseid) == courseid:
                    neighbors.append(("concept", concept))
        neighbors.extend(event_concept_neighbors(node))
        syllabus = allnodes["syllabi"].get(courseid)
        if syllabus:
            neighbors.append(("syllabus", syllabus))
        return neighbors

    if nodetype == "syllabus":
        courseid = str(getattr(node, "courseid", "") or "")
        for assignment in getattr(node, "assignments", []) or []:
            neighbors.append(("assignment", assignment))
        for fileid in getattr(node, "filechildren", []) or []:
            filenode = find_file(fileid, courseid)
            if filenode:
                neighbors.append(("file", filenode))
        return neighbors

    return neighbors


def add_result(results, seen, nodetype, node, similarity, source=None, score_parts=None):
    key = node_identity(nodetype, node)
    existing_index = seen.get(key)
    item = {
        'type': nodetype,
        'node': node,
        'similarity': float(similarity),
        'source': source
    }
    if isinstance(score_parts, dict):
        item.update(score_parts)
    if existing_index is None:
        seen[key] = len(results)
        results.append(item)
        return
    if similarity > results[existing_index].get('similarity', 0):
        results[existing_index] = item


def source_context(nodetype, node):
    return {
        "type": nodetype,
        "id": node_identity(nodetype, node)[1],
        "name": getattr(node, "name", ""),
        "description": getattr(node, "description", "")
    }


def injected_result_score(results, query, intent, mode, nodetype, node, k=5):
    base = max((item.get("similarity", 0) for item in results[:k]), default=0.0)
    adjusted = adjusted_result_similarity(base, query, intent, mode, nodetype, node)
    return max(adjusted, base + 0.01)


def drop_slot_for_promotion(top, query, intent):
    if not top:
        return top
    lowered_query = sanitize_query(query).lower()
    homework_scores = [
        (index, item.get("similarity", 0.0))
        for index, item in enumerate(top)
        if item["type"] == "assignment"
        and HOMEWORK_NUMBER_QUERY_PATTERN.search(str(getattr(item["node"], "name", "") or ""))
    ]
    best_homework_index = None
    if homework_scores and "homework" in lowered_query:
        best_homework_index = max(homework_scores, key=lambda pair: pair[1])[0]
    homework_num_match = HOMEWORK_NUMBER_QUERY_PATTERN.search(lowered_query)
    query_homework_num = homework_num_match.group(1) if homework_num_match else None

    removable = []
    for index, item in enumerate(top):
        if item["type"] != "assignment":
            removable.append(index)
            continue
        name = str(getattr(item["node"], "name", "") or "")
        lowered_name = name.lower()
        if intent == "assignment" and assignment_pset_like(name):
            match = PSET_NUMBER_QUERY_PATTERN.search(lowered_query)
            pset_num = match.group(1) if match else "1"
            if re.search(rf"(?:pset|problem set)\s*{re.escape(pset_num)}\b", lowered_name, re.I):
                continue
        if intent in {"exam", "deadline"} and assignment_exam_like(name):
            if re.search(r"\bexam\s*\d", lowered_name) or lowered_name.startswith("final exam"):
                continue
        if "homework" in lowered_query and HOMEWORK_NUMBER_QUERY_PATTERN.search(lowered_name):
            if query_homework_num and re.search(
                rf"\bhomework\s*{re.escape(query_homework_num)}\b", lowered_name, re.I
            ):
                continue
            if query_homework_num is None and index == best_homework_index:
                continue
        removable.append(index)
    drop_index = min(
        removable or [len(top) - 1],
        key=lambda index: top[index].get("similarity", 0),
    )
    return [item for index, item in enumerate(top) if index != drop_index]


def diversify_browser_exam_results(results, mode, intent, query, k=5):
    if mode != "browser" or intent != "exam" or not results:
        return results
    top = results[:k]
    if any(item["type"] in {"file", "event"} for item in top):
        return results
    best = None
    for item in results[k:]:
        if item["type"] in {"file", "event"}:
            if best is None or item.get("similarity", 0) > best.get("similarity", 0):
                best = item
    if best is None:
        for courseid, info in COURSE_CATALOG.items():
            if course_code_match_score(query, info) < COURSE_CODE_STRONG_MATCH:
                continue
            cid = str(courseid)
            for event in allnodes.get("events", []) or []:
                if str(getattr(event, "courseid", "") or "") != cid:
                    continue
                name = str(getattr(event, "name", "") or "").lower()
                if name in {"exam", "midterm review"} or (
                    "practice" in sanitize_query(query).lower() and "exam" in name
                ):
                    score = injected_result_score(results, query, intent, mode, "event", event)
                    if best is None or score > best.get("similarity", 0):
                        best = {"type": "event", "node": event, "similarity": score}
            for filenode in allnodes.get("files", {}).get(cid, {}).values():
                fname = str(getattr(filenode, "name", "") or "").lower()
                if ("practice" in fname and "exam" in fname) or "example_exam" in fname.replace(" ", "_"):
                    score = injected_result_score(results, query, intent, mode, "file", filenode)
                    if best is None or score > best.get("similarity", 0):
                        best = {"type": "file", "node": filenode, "similarity": score}
            break
    if best is None:
        return results
    diversified = drop_slot_for_promotion(list(top), query, intent) + [best]
    seen = {node_identity(item["type"], item["node"]) for item in diversified}
    for item in results:
        key = node_identity(item["type"], item["node"])
        if key in seen:
            continue
        diversified.append(item)
        seen.add(key)
        if len(diversified) >= k:
            break
    tail = [item for item in results if node_identity(item["type"], item["node"]) not in seen]
    return sorted(diversified, key=lambda item: item.get("similarity", 0), reverse=True) + tail


def promote_browser_assignment_file(results, mode, intent, query, k=5):
    if mode != "browser" or intent != "assignment" or not results:
        return results
    lowered = sanitize_query(query).lower()
    wants_file = (
        "solution" in lowered
        or bool(PSET_QUERY_PATTERN.search(lowered))
    )
    if not wants_file:
        return results
    if any(item["type"] == "file" for item in results[:k]):
        return results
    best_file = None

    def consider_file_candidate(filenode, base_score=0.0):
        nonlocal best_file
        if not file_is_primary_pset_solution(getattr(filenode, "name", ""), query):
            if not (is_course_homepage_file(filenode) and "solution" in lowered):
                return
        score = max(
            float(base_score or 0.0),
            injected_result_score(results, query, intent, mode, "file", filenode),
        )
        if file_is_primary_pset_solution(getattr(filenode, "name", ""), query):
            score += pset_solution_file_tiebreak(getattr(filenode, "name", "")) * 0.001
        candidate = {"type": "file", "node": filenode, "similarity": score}
        if best_file is None or score > best_file.get("similarity", 0):
            best_file = candidate

    for item in results[k:]:
        if item["type"] == "file":
            consider_file_candidate(item["node"], item.get("similarity", 0.0))

    for courseid, info in COURSE_CATALOG.items():
        if course_code_match_score(query, info) < COURSE_CODE_STRONG_MATCH:
            continue
        for filenode in allnodes.get("files", {}).get(str(courseid), {}).values():
            consider_file_candidate(filenode)
        if best_file is not None:
            break
    if best_file is None:
        return results
    promoted = drop_slot_for_promotion(list(results[:k]), query, intent) + [best_file]
    seen = {node_identity(item["type"], item["node"]) for item in promoted}
    for item in results:
        key = node_identity(item["type"], item["node"])
        if key in seen:
            continue
        promoted.append(item)
        seen.add(key)
        if len(promoted) >= k:
            break
    tail = [item for item in results if node_identity(item["type"], item["node"]) not in seen]
    return sorted(promoted, key=lambda item: item.get("similarity", 0), reverse=True) + tail


